#!/usr/bin/env python3
"""Write plugins/deluge-synth/src/cable_table.h: the firmware's patch sources and patchable
parameters by number and name, as tests/cable_table.cpp prints them. The plugin declares its
mod-matrix parameters before any engine exists (and the Intel build has none), so it needs them
as a fixed table. Run after moving the firmware pin; --check fails if the table is out of date.

    tools/build_firmware.py native --test tests/cable_table.cpp
    tools/gen_cables.py [--check] [root folder, default build/corpus/root]
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args = [a for a in sys.argv[1:] if a != "--check"]
root = args[0] if args else os.path.join(HERE, "build", "corpus", "root")
exe = os.path.join(HERE, "build", "firmware", "native", "cable_table")
out = subprocess.run([exe, root], capture_output=True, text=True, check=True).stdout
sources, dests = [], []
for line in out.splitlines():
    kind, number, name = (line.split(" ", 2) + [""])[:3]
    if kind == "SOURCE":
        sources.append((int(number), name))
    elif kind == "DEST":
        dests.append((int(number), name))
# What the plugin shows: the firmware's short names, in its own capitals but for the shouted ones.
NICE = {"SIDE": "Sidechain", "AFTERTOUCH": "Aftertouch", "VELOCITY": "Velocity", "NOTE": "Note", "RANDOM": "Random",
        "ENV1": "Env1", "ENV2": "Env2", "ENV3": "Env3", "ENV4": "Env4"}
for table in (sources, dests):
    assert [n for n, _ in table] == list(range(len(table))), "numbers are not 0, 1, 2 ..."
    assert all(name for _, name in table), "a number with no name"
text = ["// Generated by tools/gen_cables.py from the firmware (tests/cable_table.cpp). Do not edit.",
        "// Position in each list is the firmware's own number for the source or parameter.",
        "// SPDX-License-Identifier: GPL-3.0-or-later", "#pragma once", "", "namespace cables {", "",
        "inline constexpr const char* kSources[] = {"]
text += ['    "%s",' % NICE.get(name, name) for _, name in sources]
text += ["};", "inline constexpr int kNumSources = %d;" % len(sources), "", "inline constexpr const char* kDestinations[] = {"]
text += ['    "%s",' % name for _, name in dests]
text += ["};", "inline constexpr int kNumDestinations = %d;" % len(dests), "", "} // namespace cables", ""]
path = os.path.join(HERE, "plugins", "deluge-synth", "src", "cable_table.h")
new = "\n".join(text)
if "--check" in sys.argv:
    if not os.path.exists(path) or open(path).read() != new:
        sys.exit("cable table: %s is out of date; run tools/gen_cables.py" % os.path.relpath(path, HERE))
    print("cable table: %d sources, %d destinations, as the firmware lists them" % (len(sources), len(dests)))
else:
    open(path, "w").write(new)
    print("wrote %s: %d sources, %d destinations" % (os.path.relpath(path, HERE), len(sources), len(dests)))
